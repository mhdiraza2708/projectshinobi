def strip(t):
    return re.sub(r"\[[^\]]*\]\s*", "", t).strip()

if __name__ == "__main__":
    _, lines = mv.collect()
    out = json.load(open(HERE / "directions.json")) if len(sys.argv) > 1 and sys.argv[1] == "--merge" else {}
    for who, dirs in D.items():
        ls = [l for l in lines if l.who == who]
        assert len(ls) == len(dirs), (who, len(ls), len(dirs))
        res = []
        for l, (pre, ins) in zip(ls, dirs):
            t = l.spoken
            for sub, tag in ins:
                assert sub in t, (who, sub)
                t = t.replace(sub, f"{tag} {sub}", 1)
            t = f"{pre} {t}"
            assert strip(t) == l.spoken, (who, t)
            res.append({"key": l.key, "prompt": t})
        out[who] = res
    json.dump(out, open(HERE / "directions.json", "w"), indent=1)
    for who in D:
        for i, r in enumerate(out[who]):
            print(who, i, "|", r["prompt"])
